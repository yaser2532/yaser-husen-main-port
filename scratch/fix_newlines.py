import sys
import subprocess

sys.stdout.reconfigure(encoding='utf-8')

files = [
    'assets/css/style.css',
    'index.html',
    'assets/css/drones.css',
    'assets/js/drones.js',
    'assets/js/script.js'
]

for file_path in files:
    with open(file_path, 'rb') as f:
        raw_bytes = f.read()
    
    # Check if file has \r\r\n
    count_rrn = raw_bytes.count(b'\r\r\n')
    text = raw_bytes.decode('utf-8')
    # Replace \r\r\n with \n, then replace \r\n with \n
    text_clean = text.replace('\r\r\n', '\n').replace('\r\n', '\n')
    
    # If the file originally had double blank lines generated by previous scripts:
    # let's see how git diff looks if we write text_clean with \n
    with open(file_path, 'wb') as f:
        f.write(text_clean.encode('utf-8'))
    
    print(f"{file_path}: had {count_rrn} \\r\\r\\n sequences, cleaned to LF.")
